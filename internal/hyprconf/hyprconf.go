// Package hyprconf writes the Hyprland settings inua manages (config.toml's
// [input] and [[shortcuts]]) to hypr/inua.conf next to hyprland.conf, which sources it after
// its own settings. Hyprland reads the file at start and on every reload
// (including the one it does when the file changes), so the settings hold
// without inua-shell running.
package hyprconf

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"

	"github.com/lyricat/inua/internal/config"
	"github.com/lyricat/inua/internal/hypr"
)

// Name is the file's name in the Hyprland config directory.
const Name = "inua.conf"

// header starts every generated file.
const header = `# Generated by inua from ~/.config/inua/config.toml; changes
# here are overwritten. Use inua's settings window, or edit config.toml and
# run ` + "`inua config apply`" + `. hyprland.conf sources this file after its own
# input settings, so these win.
`

// lockRestore lets a lock screen take over Hyprland's session lock from
// one that went away, so a shell that stops while the screen is locked
// shows its lock screen again when it starts.
const lockRestore = `
# inua's lock screen holds the session lock. If the shell stops while the
# screen is locked, the screen stays locked; inua-shell, started again,
# takes the lock over and shows its lock screen.
misc {
    allow_session_lock_restore = true
}

# inua's light apps (Clock, Weather, Stocks, Calculator, Calendar, Color
# Picker, System Monitor, Viewer) float at their own size.
windowrule {
    name = inua-light-apps
    match:class = ^(io\.github\.lyricat\.Inua\..+)$
    float = yes
    center = yes
}
`

// Path is inua.conf for the settings file at configPath: both live under
// the same config directory ($XDG_CONFIG_HOME/inua/config.toml,
// $XDG_CONFIG_HOME/hypr/inua.conf).
func Path(configPath string) string {
	return filepath.Join(filepath.Dir(filepath.Dir(configPath)), "hypr", Name)
}

// Render is the file for the settings. Touchpad settings go in one device
// block per touchpad, since Hyprland has no touchpad-wide speed.
func Render(c config.Config, touchpads []string) string {
	in := c.Input
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(lockRestore)
	wrote := false
	if in.KbOptions != nil {
		fmt.Fprintf(&b, "\ninput {\n    kb_options = %s\n}\n", *in.KbOptions)
		wrote = true
	}
	if in.TouchpadSpeed != nil || in.TouchpadAccel != "" {
		for _, name := range touchpads {
			fmt.Fprintf(&b, "\ndevice {\n    name = %s\n", name)
			if in.TouchpadSpeed != nil {
				fmt.Fprintf(&b, "    sensitivity = %s\n", strconv.FormatFloat(*in.TouchpadSpeed, 'f', 2, 64))
			}
			if in.TouchpadAccel != "" {
				fmt.Fprintf(&b, "    accel_profile = %s\n", in.TouchpadAccel)
			}
			b.WriteString("}\n")
			wrote = true
		}
	}
	if !wrote && len(c.Shortcuts) == 0 {
		b.WriteString("\n# Nothing set in inua; hyprland.conf decides.\n")
	}
	renderShortcuts(&b, c)
	return b.String()
}

var (
	nameRe     = regexp.MustCompile(`^[a-z0-9][a-z0-9:._-]*$`)
	nameLineRe = regexp.MustCompile(`(?m)^\s*name\s*=\s*(\S+)\s*$`)
	touchpadRe = regexp.MustCompile(`touchpad|trackpad`)
)

// Touchpads lists the pointer devices in a j/devices reply that are
// touchpads, by Hyprland's device name.
func Touchpads(devices []byte) ([]string, error) {
	var d struct {
		Mice []struct {
			Name string `json:"name"`
		} `json:"mice"`
	}
	if err := json.Unmarshal(devices, &d); err != nil {
		return nil, err
	}
	var names []string
	for _, m := range d.Mice {
		if touchpadRe.MatchString(m.Name) && nameRe.MatchString(m.Name) {
			names = append(names, m.Name)
		}
	}
	return names, nil
}

// known lists the device names in a file Render wrote, so a touchpad that
// is unplugged when the file is written (a Bluetooth one) keeps its block.
func known(file string) []string {
	var names []string
	for _, m := range nameLineRe.FindAllStringSubmatch(file, -1) {
		if nameRe.MatchString(m[1]) {
			names = append(names, m[1])
		}
	}
	return names
}

// Apply writes the file for in at path if it differs from what is there.
// Hyprland reloads by itself when a file it sources changes; Apply asks it
// to only if that is turned off (misc:disable_autoreload), since every
// reload also redoes monitors. client may be nil (Hyprland not running):
// the file is still written, and Hyprland reads it when it starts. changed
// reports whether the file was rewritten.
func Apply(ctx context.Context, c config.Config, path string, client *hypr.Client) (changed bool, err error) {
	old, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	touchpads := known(string(old))
	if client != nil {
		reply, err := client.Request(ctx, "j/devices")
		if err != nil {
			return false, fmt.Errorf("hyprland devices: %w", err)
		}
		now, err := Touchpads(reply)
		if err != nil {
			return false, fmt.Errorf("hyprland devices: %w", err)
		}
		touchpads = append(touchpads, now...)
	}
	slices.Sort(touchpads)
	touchpads = slices.Compact(touchpads)

	want := Render(c, touchpads)
	if string(old) == want {
		return false, nil
	}
	if err := write(path, want); err != nil {
		return false, err
	}
	if client == nil {
		return true, nil
	}
	if auto, err := autoreload(ctx, client); err != nil || auto {
		return true, err
	}
	reply, err := client.Request(ctx, "reload")
	if err != nil {
		return true, fmt.Errorf("hyprland reload: %w", err)
	}
	if r := strings.TrimSpace(string(reply)); r != "ok" {
		return true, fmt.Errorf("hyprland reload: %s", r)
	}
	return true, nil
}

// autoreload reports whether Hyprland reloads when its config files change.
func autoreload(ctx context.Context, client *hypr.Client) (bool, error) {
	reply, err := client.Request(ctx, "j/getoption misc:disable_autoreload")
	if err != nil {
		return false, fmt.Errorf("hyprland: %w", err)
	}
	var opt struct {
		Int int `json:"int"`
	}
	if err := json.Unmarshal(reply, &opt); err != nil {
		return false, fmt.Errorf("hyprland: misc:disable_autoreload: %w", err)
	}
	return opt.Int == 0, nil
}

// write replaces path in one step, so Hyprland never reads half a file.
func write(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".inua-*.conf")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name()) // a no-op once renamed
	if _, err := tmp.WriteString(content); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
