// RenderLua is inua.lua for the settings, the Lua form of Render.
func RenderLua(c config.Config, d Devices) string {
	touchpads := d.Touchpads
	in := c.Input
	var b strings.Builder
	b.WriteString(luaHeader)
	wrote := false
	if in.KbOptions != nil {
		fmt.Fprintf(&b, "\nhl.config({ input = { kb_options = %s } })\n", luaString(*in.KbOptions))
		wrote = true
	}
	if in.TouchpadSpeed != nil || in.TouchpadAccel != "" {
		for _, name := range touchpads {
			fmt.Fprintf(&b, "\nhl.device({\n    name = %s,\n", luaString(name))
			if in.TouchpadSpeed != nil {
				fmt.Fprintf(&b, "    sensitivity = %s,\n", strconv.FormatFloat(*in.TouchpadSpeed, 'f', 2, 64))
			}
			if in.TouchpadAccel != "" {
				fmt.Fprintf(&b, "    accel_profile = %s,\n", luaString(in.TouchpadAccel))
			}
			b.WriteString("})\n")
			wrote = true
		}
	}
	if !wrote && len(c.Shortcuts) == 0 && !writesDisplays(c, d) {
		b.WriteString("\n-- Nothing set in inua; hyprland.lua decides.\n")
	}
	renderDisplaysLua(&b, c, d)
	renderShortcutsLua(&b, c)
	return b.String()
}

// luaString is s as a Lua string literal.
func luaString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		switch c := s[i]; {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '\n':
			b.WriteString(`\n`)
		case c < 0x20 || c == 0x7f:
			fmt.Fprintf(&b, `\%03d`, c)
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

var (
	nameRe     = regexp.MustCompile(`^[a-z0-9][a-z0-9:._-]*$`)
	nameLineRe = regexp.MustCompile(`(?m)^\s*name\s*=\s*(\S+)\s*$`)
	luaNameRe  = regexp.MustCompile(`hl\.device\(\{\s*name\s*=\s*"([^"]+)"`)
	touchpadRe = regexp.MustCompile(`touchpad|trackpad`)
)

// Touchpads lists the pointer devices in a j/devices reply that are
// touchpads, by Hyprland's device name.
func Touchpads(devices []byte) ([]string, error) {
	var d struct {
		Mice []struct {
			Name string `json:"name"`
		} `json:"mice"`
	}
	if err := json.Unmarshal(devices, &d); err != nil {
		return nil, err
	}
	var names []string
	for _, m := range d.Mice {
		if touchpadRe.MatchString(m.Name) && nameRe.MatchString(m.Name) {
			names = append(names, m.Name)
		}
	}
	return names, nil
}

// known lists the device names in a file Render or RenderLua wrote, so a touchpad that
// is unplugged when the file is written (a Bluetooth one) keeps its block.
// The lid switches are knownLids.
func known(file string) []string {
	var names []string
	re := nameLineRe
	if strings.HasPrefix(file, "--") {
		re = luaNameRe
	}
	for _, m := range re.FindAllStringSubmatch(file, -1) {
		if nameRe.MatchString(m[1]) {
			names = append(names, m[1])
		}
	}
	return names
}

// Apply writes the file for in at path (inua.conf, or inua.lua: see
// Target) if it differs from what is there. The built-in display is off in
// it while the lid is closed and another display is connected (lid_off),
// so Apply runs again when the lid moves (LidCommand) and when a monitor
// comes or goes.
// Hyprland reloads by itself when a file it sources changes; Apply asks it
// to only if that is turned off (misc:disable_autoreload), since every
// reload also redoes monitors. client may be nil (Hyprland not running):
// the file is still written, and Hyprland reads it when it starts. changed
// reports whether the file was rewritten.
func Apply(ctx context.Context, c config.Config, path string, client *hypr.Client) (changed bool, err error) {
	old, err := os.ReadFile(path)
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	d := Devices{Touchpads: known(string(old)), Lids: knownLids(string(old))}
	if client != nil {
		reply, err := client.Request(ctx, "j/devices")
		if err != nil {
			return false, fmt.Errorf("hyprland devices: %w", err)
		}
		now, err := Touchpads(reply)
		if err != nil {
			return false, fmt.Errorf("hyprland devices: %w", err)
		}
		d.Touchpads = append(d.Touchpads, now...)
		lids, err := Lids(reply)
		if err != nil {
			return false, fmt.Errorf("hyprland devices: %w", err)
		}
		d.Lids = append(d.Lids, lids...)
	}
	for _, names := range []*[]string{&d.Touchpads, &d.Lids} {
		slices.Sort(*names)
		*names = slices.Compact(*names)
	}
	if c.Displays.LidOff {
		d.PanelsOff = panelsOff()
	}

	want := Render(c, d)
	if strings.HasSuffix(path, ".lua") {
		want = RenderLua(c, d)
	}
	if string(old) == want {
		return false, nil
	}
	if err := write(path, want); err != nil {
		return false, err
	}
	if client == nil {
		return true, nil
	}
	if auto, err := autoreload(ctx, client); err != nil || auto {
		return true, err
	}
	reply, err := client.Request(ctx, "reload")
	if err != nil {
		return true, fmt.Errorf("hyprland reload: %w", err)
	}
	if r := strings.TrimSpace(string(reply)); r != "ok" {
		return true, fmt.Errorf("hyprland reload: %s", r)
	}
	return true, nil
}

// autoreload reports whether Hyprland reloads when its config files change.
func autoreload(ctx context.Context, client *hypr.Client) (bool, error) {
	reply, err := client.Request(ctx, "j/getoption misc:disable_autoreload")
	if err != nil {
		return false, fmt.Errorf("hyprland: %w", err)
	}
	var opt struct {
		Int int `json:"int"`
	}
	if err := json.Unmarshal(reply, &opt); err != nil {
		return false, fmt.Errorf("hyprland: misc:disable_autoreload: %w", err)
	}
	return opt.Int == 0, nil
}

// write replaces path in one step, so Hyprland never reads half a file.
func write(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".inua-*.conf")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name()) // a no-op once renamed
	if _, err := tmp.WriteString(content); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}
