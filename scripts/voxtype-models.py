#!/usr/bin/env python3
"""Write internal/system/voxtype_models_info.go from voxtype's model tables.

    scripts/voxtype-models.py path/to/voxtype/src/setup/model.rs VERSION \\
        | gofmt > internal/system/voxtype_models_info.go

The file is voxtype's own, at the release inua pins (VoxtypeVersion), e.g.
    gh api 'repos/peteonrails/voxtype/contents/src/setup/model.rs?ref=v1.1.1' \\
        --jq .content | base64 -d > /tmp/model.rs
"""
import re
import sys

TABLES = [("MODELS", "whisper"), ("PARAKEET_MODELS", "parakeet"), ("MOONSHINE_MODELS", "moonshine"),
          ("SENSEVOICE_MODELS", "sensevoice"), ("PARAFORMER_MODELS", "paraformer"), ("DOLPHIN_MODELS", "dolphin"),
          ("OMNILINGUAL_MODELS", "omnilingual"), ("COHERE_MODELS", "cohere"), ("OPENVINO_MODELS", "openvino")]
# Parakeet's table has no languages; these are its model cards'.
EU25 = "bg/cs/da/de/el/en/es/et/fi/fr/hr/hu/it/lt/lv/mt/nl/pl/pt/ro/ru/sk/sl/sv/uk"


def closing(text, start, open_, close):
    depth = 0
    for j in range(start, len(text)):
        if text[j] == open_:
            depth += 1
        elif text[j] == close:
            depth -= 1
            if depth == 0:
                return j
    raise ValueError("unbalanced")


def main(path, version):
    src = open(path).read()
    rows = []
    for const, engine in TABLES:
        i = src.index("= &[", re.search(r"\nconst " + const + r":", src).start()) + 3
        body = src[i + 1:closing(src, i, "[", "]")]
        for m in re.finditer(r"\b\w*ModelInfo \{", body):
            entry = body[m.end():closing(body, m.end() - 1, "{", "}")]

            def field(key):
                f = re.search(r"\b" + key + r':\s*"([^"]*)"', entry)
                return f.group(1) if f else ""

            name, size = field("name"), int(re.search(r"size_mb:\s*(\d+)", entry).group(1))
            langs = field("languages") or field("language")
            if engine == "whisper":
                langs = "en" if "english_only: true" in entry else "*"
            elif engine == "openvino":
                langs = "en" if ".en" in name else "*"
            elif engine == "parakeet":
                langs = EU25 if "v3" in name else "en"
            for key in dict.fromkeys(k for k in (name, field("dir_name")) if k):
                rows.append((engine, key, size, langs.replace(",", "/")))
    print(f"// Code generated by scripts/voxtype-models.py from voxtype {version}'s")
    print("// src/setup/model.rs; DO NOT EDIT. With a new VoxtypeVersion, run it again.")
    print()
    print("package system")
    print()
    print("// voxtypeModelInfo is a model's download size in MB and its languages")
    print('// ("zh/en/ja/ko/yue"; "*" for Whisper\'s many), by engine and the name or')
    print("// folder `voxtype info models` gives.")
    print("var voxtypeModelInfo = map[[2]string]struct {")
    print("\tMB    int")
    print("\tLangs string")
    print("}{")
    for engine, key, size, langs in rows:
        print(f'\t{{"{engine}", "{key}"}}: {{{size}, "{langs}"}},')
    print("}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
